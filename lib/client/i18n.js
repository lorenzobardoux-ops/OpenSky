  const TABLES = { de: DE };
  const LANGUAGES = { en: "English", de: "Deutsch" };

  const fill = (s, vars) => (vars ? String(s).replace(/\{(\w+)\}/g, (m, k) => (vars[k] == null ? m : String(vars[k]))) : String(s));
  const short = (l) => String(l || "en").toLowerCase().split(/[-_]/)[0];

  let lang = null, forced = null;
  // node: the language comes from the settings file (re-read when it changes; a restart isn't needed for messages)
  let settingsFile = null, settingsMtime = 0;
  function nodeLanguage() {
    try {
      const fs = require("fs");
      const file = process.env.OPENSKY_SETTINGS;
      if (!file) return "en";
      const m = fs.statSync(file).mtimeMs;
      if (file !== settingsFile || m !== settingsMtime) {
        settingsFile = file; settingsMtime = m;
        lang = short(((JSON.parse(fs.readFileSync(file, "utf8")).locale) || {}).language);
      }
      return lang;
    } catch (e) { return lang || "en"; }
  }
  function language() {
    if (forced) return forced;
    if (typeof window === "undefined") return nodeLanguage();
    // eslint-disable-next-line no-undef
    return short(typeof config !== "undefined" && config && config.language);
  }

  const api = {
    LANGUAGES,
    TABLES,
    language,
    /** The phone page (and tests) set the language themselves. */
    setLanguage(l) { forced = short(l); },
    t(text, vars) { return api.tFor(language(), text, vars); },
    /** A given language (config.js builds the screen for opensky.json's language). */
    tFor(l, text, vars) {
      const table = TABLES[short(l)];
      const out = table && Object.prototype.hasOwnProperty.call(table, text) ? table[text] : text;
      return fill(out, vars);
    }

  };
  api.osT = api.t;

  if (typeof module !== "undefined" && module.exports) module.exports = api;
  if (typeof window !== "undefined") {
    if (!window.OpenSkyI18n) { window.OpenSkyI18n = api; window.osT = api.t; }
  }
